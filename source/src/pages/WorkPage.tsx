import { useEffect, useState } from "react"
import GlassFolder, { type ArtRecipe, type FolderFile } from "@/components/ui/glass-folder-cards"
import { PROJECTS, projectUrl } from "@/data/projects"

const bySlug = (slug: string) => PROJECTS.find((p) => p.slug === slug)!

/** A project as a file in a folder: its cover, opening its page on this site. */
const projectFile = (slug: string, meta: string): FolderFile => {
  const p = bySlug(slug)
  return { name: p.title, meta, image: p.cover.src, href: projectUrl(p) }
}

const graphic = bySlug("graphic-design")
const poster = (page: string, name: string, meta: string): FolderFile => ({
  name,
  meta,
  image: `/projects/graphic/${page}.webp`,
  href: projectUrl(graphic),
})

/**
 * Folder artwork: dark marbled liquid, one muted hue per folder so all four
 * sit on the near-black page. Generated by the folder component itself.
 */
const marble = (colors: string[]): ArtRecipe => ({
  style: "marble",
  colors,
  scale: 0.55,
  warp: 3.4,
  angle: -0.5,
  gloss: 0.35,
  veins: 0.55,
})
const ART = {
  // steel blue
  uiux: marble(["#020305", "#080b10", "#18222f", "#050608", "#34465e", "#7a8ea8", "#bccad9"]),
  // graphite and silver
  branding: marble(["#030303", "#0b0b0b", "#222222", "#060606", "#4d4d4d", "#9a9a9a", "#d2d2d2"]),
  // deep teal
  product: marble(["#020403", "#060c0a", "#10221d", "#040706", "#23453c", "#5a8579", "#9cbfb4"]),
  // dusky plum
  graphics: marble(["#030204", "#0b0810", "#1e1626", "#060408", "#3d3150", "#7a6c90", "#b1a5c4"]),
}

